import * as path from "path";
import * as vscode from "vscode";
import { AddonDocsManager } from "../data/addonDocsManager";
import { findPluginsDir, generatedDocsPath, listJars, matchAddons } from "../data/serverPlugins";

const DECLINED_KEY = "r4tsk.serverPlugins.declined";

function updateTarget(): vscode.ConfigurationTarget {
  return vscode.workspace.workspaceFolders && vscode.workspace.workspaceFolders.length > 0
    ? vscode.ConfigurationTarget.Workspace
    : vscode.ConfigurationTarget.Global;
}

function candidateStartPaths(): string[] {
  const starts = (vscode.workspace.workspaceFolders ?? []).map((f) => f.uri.fsPath);
  for (const editor of vscode.window.visibleTextEditors) {
    if (editor.document.languageId === "skript" && editor.document.uri.scheme === "file") {
      starts.push(path.dirname(editor.document.uri.fsPath));
    }
  }
  return starts;
}

/**
 * Looks for a Skript server's plugins folder around the workspace. Addon jars
 * that match SkriptHub addons, and a docs.json generated by `/sk gen-docs`, are
 * offered once; accepting stores them in `r4tsk.addons` and
 * `r4tsk.additionalDocsPaths`, which the config listener applies live.
 */
export async function checkServerPlugins(context: vscode.ExtensionContext, manager: AddonDocsManager): Promise<void> {
  const cfg = vscode.workspace.getConfiguration("r4tsk");
  if (!cfg.get<boolean>("detectServerAddons", true)) return;

  const dirs = [...new Set(candidateStartPaths().map(findPluginsDir).filter((d): d is string => d !== undefined))];
  const declined = context.globalState.get<string[]>(DECLINED_KEY, []);

  for (const pluginsDir of dirs) {
    if (declined.includes(pluginsDir)) continue;

    const jars = listJars(pluginsDir);
    let matched: string[] = [];
    if (jars.length > 0) {
      try {
        const names = [...new Set((await manager.client.getSyntax()).entries.map((e) => e.addon.name))];
        matched = matchAddons(jars, names);
      } catch {
        matched = [];
      }
    }
    const selected = new Set(cfg.get<string[]>("addons", []).map((n) => n.toLowerCase()));
    const newAddons = matched.filter((n) => !selected.has(n.toLowerCase()));

    const docs = generatedDocsPath(pluginsDir);
    const known = new Set(cfg.get<string[]>("additionalDocsPaths", []).map((p) => path.resolve(p)));
    const newDocs = docs && !known.has(path.resolve(docs)) ? docs : undefined;

    if (newAddons.length === 0 && !newDocs) continue;

    const found = [
      newAddons.length > 0 ? newAddons.join(", ") : undefined,
      newDocs ? "a generated docs.json" : undefined,
    ].filter(Boolean);
    const use = "Use them";
    const never = "Never for this folder";
    const choice = await vscode.window.showInformationMessage(
      `r4tsk found ${found.join(" and ")} in ${pluginsDir}. Use them?`,
      use,
      never
    );
    if (choice === use) {
      const target = updateTarget();
      if (newAddons.length > 0) {
        const current = cfg.inspect<string[]>("addons")?.workspaceValue ?? cfg.get<string[]>("addons", []);
        await cfg.update("addons", [...new Set([...current, ...newAddons])], target);
      }
      if (newDocs) {
        const current = cfg.inspect<string[]>("additionalDocsPaths")?.workspaceValue ?? cfg.get<string[]>("additionalDocsPaths", []);
        await cfg.update("additionalDocsPaths", [...new Set([...current, newDocs])], target);
      }
    } else if (choice === never) {
      await context.globalState.update(DECLINED_KEY, [...declined, pluginsDir]);
    }
  }
}
